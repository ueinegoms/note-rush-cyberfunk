#!/usr/bin/env python3
"""
copilot_gate.py — Tiny HTTP server that accepts an authenticated POST
request and triggers reprompt.sh (which re-prompts VS Code Copilot Chat).

Start:  python3 scripts/copilot_gate.py
Port:   8081 (hardcoded; change GATE_PORT below if needed)

Endpoints:
  POST /resume/<SECRET>  → runs reprompt.sh, returns 200 + log snippet
  All other requests     → 403 (no info leaked)

Secret loaded from:  <repo-root>/.gate-secret
(generated by setup-cron.sh; never committed to git)
"""

import http.server
import subprocess
import os
import sys
import logging
import time

GATE_PORT = 8081
LOG_FILE  = "/tmp/gate.log"

# ── Locate repo root and script dir ─────────────────────────────────────────
SCRIPT_DIR = os.path.dirname(os.path.realpath(__file__))
REPO_ROOT  = os.path.abspath(os.path.join(SCRIPT_DIR, ".."))
SECRET_FILE = os.path.join(REPO_ROOT, ".gate-secret")
REPROMPT_SH = os.path.join(SCRIPT_DIR, "reprompt.sh")

logging.basicConfig(
    filename=LOG_FILE,
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
    datefmt="%Y-%m-%d %H:%M:%S",
)

def load_secret():
    if not os.path.exists(SECRET_FILE):
        logging.error("SECRET FILE NOT FOUND: %s — run setup-cron.sh first", SECRET_FILE)
        sys.exit(1)
    secret = open(SECRET_FILE).read().strip()
    if len(secret) < 8:
        logging.error("Secret too short — regenerate with setup-cron.sh")
        sys.exit(1)
    return secret

SECRET = load_secret()

class GateHandler(http.server.BaseHTTPRequestHandler):
    def log_message(self, fmt, *args):
        # Route access log into our file instead of stderr
        logging.info("HTTP %s - %s", self.address_string(), fmt % args)

    def do_POST(self):
        expected = "/resume/" + SECRET
        if self.path != expected:
            self.send_response(403)
            self.end_headers()
            # No body — don't reveal expected path format
            return

        self.send_response(200)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.end_headers()

        logging.info("TRIGGER received — running reprompt.sh")
        try:
            env = os.environ.copy()
            env.setdefault("DISPLAY", ":0")
            result = subprocess.run(
                ["bash", REPROMPT_SH],
                capture_output=True,
                text=True,
                timeout=20,
                env=env,
            )
            output = (result.stdout + result.stderr).strip()[-500:]  # last 500 chars
            self.wfile.write(("OK\n" + output + "\n").encode())
            logging.info("reprompt.sh exited code=%d", result.returncode)
        except subprocess.TimeoutExpired:
            self.wfile.write(b"TIMEOUT\n")
            logging.error("reprompt.sh timed out")
        except Exception as exc:
            self.wfile.write(b"ERROR\n")
            logging.exception("reprompt.sh exception: %s", exc)

    def do_GET(self):
        self.send_response(403)
        self.end_headers()


if __name__ == "__main__":
    server = http.server.HTTPServer(("127.0.0.1", GATE_PORT), GateHandler)
    logging.info("Gate server listening on 127.0.0.1:%d", GATE_PORT)
    print(f"Gate server listening on http://127.0.0.1:{GATE_PORT}")
    print(f"Secret loaded from: {SECRET_FILE}")
    print(f"Logs: {LOG_FILE}")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        logging.info("Gate server stopped.")
        print("\nGate server stopped.")
